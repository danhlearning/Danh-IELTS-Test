const modeOrder = ['letter_fill', 'meaning_match', 'collocation', 'word_class', 'preposition', 'sentence_cloze'];

// Group base35 by word prefix so letter_fill and meaning_match can use the real contextual sentences from collocation/sentence_cloze
const base35ByPrefix = {};
base35Toeic.forEach(q => {
  const prefix = q.id.split('_').slice(0, 2).join('_');
  if (!base35ByPrefix[prefix]) base35ByPrefix[prefix] = {};
  base35ByPrefix[prefix][q.mode] = q;
});

const updatedExistingToeic = base35Toeic.map(q => {
  const rootWord = q.target_word.split(' ')[0].toUpperCase();
  const prefix = q.id.split('_').slice(0, 2).join('_');
  const group = base35ByPrefix[prefix] || {};
  const cfg = tierMapExisting[rootWord] || { tier: 'toeic500', label: 'TOEIC 500-550', bands: ['TOEIC 500', 'TOEIC 500', 'TOEIC 550', 'TOEIC 550', 'TOEIC 550', 'TOEIC 550'] };
  const mIdx = Math.max(0, modeOrder.indexOf(q.mode));

  let realSentence = q.real_exam_sentence;
  if (realSentence && (realSentence.startsWith('TOEIC Essential:') || realSentence.startsWith('In business contexts:'))) {
    if (q.mode === 'letter_fill' && group.collocation && group.collocation.real_exam_sentence) {
      realSentence = group.collocation.real_exam_sentence;
    } else if (q.mode === 'meaning_match' && group.sentence_cloze && group.sentence_cloze.real_exam_sentence) {
      realSentence = group.sentence_cloze.real_exam_sentence;
    }
  }

  return {
    ...q,
    toeic_tier: cfg.tier,
    grade_label: cfg.label,
    band: cfg.bands[mIdx] || cfg.bands[0],
    real_exam_sentence: realSentence
  };
});

